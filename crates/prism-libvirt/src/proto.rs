/// `remote_node_get_info_ret`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NodeInfo {
    /// CPU model string, at most 31 characters.
    pub model: String,
    /// Host memory in KiB.
    pub memory_kib: u64,
    /// Number of active CPUs.
    pub cpus: i32,
    /// CPU frequency in MHz.
    pub mhz: i32,
    /// Number of NUMA nodes.
    pub nodes: i32,
    /// Sockets per NUMA node.
    pub sockets: i32,
    /// Cores per socket.
    pub cores: i32,
    /// Threads per core.
    pub threads: i32,
}

impl NodeInfo {
    /// Reads a node info reply.
    pub fn decode(d: &mut Decoder<'_>) -> Result<Self, Error> {
        // `char model[32]` is an XDR vector of chars, each a 4-byte unit.
        let mut model = Vec::with_capacity(32);
        for _ in 0..32 {
            model.push(d.u32()? as u8);
        }
        let end = model.iter().position(|&b| b == 0).unwrap_or(model.len());
        Ok(Self {
            model: String::from_utf8_lossy(&model[..end]).into_owned(),
            memory_kib: d.u64()?,
            cpus: d.i32()?,
            mhz: d.i32()?,
            nodes: d.i32()?,
            sockets: d.i32()?,
            cores: d.i32()?,
            threads: d.i32()?,
        })
    }
}

