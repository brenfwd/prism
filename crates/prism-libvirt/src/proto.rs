/// `remote_nonnull_domain`: a reference to a domain.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Domain {
    /// Domain name, unique on the host.
    pub name: String,
    /// Domain UUID.
    pub uuid: [u8; UUID_LEN],
    /// Runtime ID, or -1 when the domain is not running.
    pub id: i32,
}

impl Domain {
    /// Appends the domain reference.
    pub fn encode(&self, e: &mut Encoder) {
        e.string(&self.name).opaque_fixed(&self.uuid).i32(self.id);
    }

    /// Reads a domain reference.
    pub fn decode(d: &mut Decoder<'_>) -> Result<Self, Error> {
        let name = d.string()?;
        let mut uuid = [0; UUID_LEN];
        uuid.copy_from_slice(d.opaque_fixed(UUID_LEN)?);
        Ok(Self {
            name,
            uuid,
            id: d.i32()?,
        })
    }
}

/// `virDomainState`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DomainState {
    /// No state reported.
    NoState,
    /// Running.
    Running,
    /// Blocked on a resource.
    Blocked,
    /// Paused by the user or the hypervisor.
    Paused,
    /// Shutting down.
    Shutdown,
    /// Powered off.
    Shutoff,
    /// Crashed.
    Crashed,
    /// Suspended by the guest's power management.
    PmSuspended,
    /// A state code this client does not know.
    Unknown(i32),
}

impl From<i32> for DomainState {
    fn from(v: i32) -> Self {
        match v {
            0 => Self::NoState,
            1 => Self::Running,
            2 => Self::Blocked,
            3 => Self::Paused,
            4 => Self::Shutdown,
            5 => Self::Shutoff,
            6 => Self::Crashed,
            7 => Self::PmSuspended,
            v => Self::Unknown(v),
        }
    }
}

