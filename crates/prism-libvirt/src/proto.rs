/// `virNetMessageType`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u32)]
pub enum MessageType {
    /// A request from the client.
    Call = 0,
    /// The answer to a call, matched by serial.
    Reply = 1,
    /// An unsolicited message such as an event or a keepalive ping.
    Message = 2,
    /// Data or a status change on an open stream.
    Stream = 3,
    /// A call that passes file descriptors (unused).
    CallWithFds = 4,
    /// A reply that passes file descriptors (unused).
    ReplyWithFds = 5,
    /// A sparse-stream hole marker (unused).
    StreamHole = 6,
}

impl TryFrom<u32> for MessageType {
    type Error = Error;
    fn try_from(v: u32) -> Result<Self, Error> {
        Ok(match v {
            0 => Self::Call,
            1 => Self::Reply,
            2 => Self::Message,
            3 => Self::Stream,
            4 => Self::CallWithFds,
            5 => Self::ReplyWithFds,
            6 => Self::StreamHole,
            _ => return Err(Error::Decode(format!("bad message type {v}"))),
        })
    }
}

/// `virNetMessageStatus`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u32)]
pub enum Status {
    /// The call succeeded, or the stream ended normally.
    Ok = 0,
    /// The call failed; the body is a [`RemoteError`].
    Error = 1,
    /// A stream message that carries data.
    Continue = 2,
}

impl TryFrom<u32> for Status {
    type Error = Error;
    fn try_from(v: u32) -> Result<Self, Error> {
        Ok(match v {
            0 => Self::Ok,
            1 => Self::Error,
            2 => Self::Continue,
            _ => return Err(Error::Decode(format!("bad message status {v}"))),
        })
    }
}

/// `virNetMessageHeader`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Header {
    /// RPC program number.
    pub prog: u32,
    /// Program version.
    pub vers: u32,
    /// Procedure number.
    pub proc: u32,
    /// Message kind.
    pub ty: MessageType,
    /// Call serial; replies and stream messages repeat the call's serial.
    pub serial: u32,
    /// Outcome of the call, or the kind of stream message.
    pub status: Status,
}

impl Header {
    /// Appends the 24-byte header.
    pub fn encode(&self, e: &mut Encoder) {
        e.u32(self.prog)
            .u32(self.vers)
            .u32(self.proc)
            .u32(self.ty as u32)
            .u32(self.serial)
            .u32(self.status as u32);
    }

    /// Reads a header. Fails on an unknown message type or status.
    pub fn decode(d: &mut Decoder<'_>) -> Result<Self, Error> {
        Ok(Self {
            prog: d.u32()?,
            vers: d.u32()?,
            proc: d.u32()?,
            ty: d.u32()?.try_into()?,
            serial: d.u32()?,
            status: d.u32()?.try_into()?,
        })
    }
}

